// Authoring tool (not loaded by the page): deals the lane queues for every
// level, checks each one with the solver, measures how much planning it needs,
// and writes queues.js. Run from the repo root:  node proto/lift/gen-levels.mjs
// Deterministic: the same code and seeds always write the same file.
import { writeFileSync } from 'node:fs';
import { LEVEL_DEFS } from './levels.js';
import { buildLevel, generateQueues, solve, casualRate, replay, isDone, capacitiesMatch } from './rules.js';

// How often a casual player (lift when you can, otherwise tap anything) should
// clear the picture without help: early levels nearly always, later ones less.
const TARGET = [0.97, 0.9, 0.85, 0.8, 0.7, 0.65, 0.6, 0.5, 0.45, 0.4, 0.35, 0.3];
// Chance that the intended order promises a jar to a still-buried color.
const FUTURE = [0, 0.05, 0.1, 0.15, 0.2, 0.25, 0.3, 0.3, 0.35, 0.35, 0.4, 0.4];
const SEEDS = +(process.env.SEEDS || 150);

const out = [];
for (const [idx, def] of LEVEL_DEFS.entries()) {
  const base = buildLevel(def);
  let best = null;
  for (let seed = 1; seed <= SEEDS; seed++) {
    const g = generateQueues(base, { lanes: def.lanes, seed, future: FUTURE[idx] });
    if (!g) continue;
    const L = buildLevel({ ...def, queues: g.queues });
    if (!capacitiesMatch(L)) throw new Error(`${def.id}: capacities do not match`);
    const rate = casualRate(L, 99 + seed, 80);
    const sol = solve(L, undefined, { cap: 60000 });
    if (!sol.ok) continue;
    const d = Math.abs(rate - TARGET[idx]);
    if (!best || d < best.d - 1e-9) best = { d, seed, queues: g.queues, rate, sol, jars: g.intended };
  }
  if (!best) throw new Error(`${def.id}: no solvable layout found`);
  const L = buildLevel({ ...def, queues: best.queues });
  if (!isDone(replay(L, best.sol.path))) throw new Error(`${def.id}: solution does not replay`);
  out.push({ id: def.id, seed: best.seed, queues: best.queues, solution: best.sol.path.join(' '),
    stats: { jars: best.jars, moves: best.sol.path.length, nodes: best.sol.nodes, casual: +best.rate.toFixed(2) } });
  console.log(`${def.id.padEnd(11)} ${L.W}x${L.H} ${L.colors.length} colors  jars ${best.jars}  seed ${best.seed}  solution ${best.sol.path.length} moves (${best.sol.nodes} nodes)  casual clear ${(best.rate * 100).toFixed(0)}% (target ${TARGET[idx] * 100}%)`);
}

const body = out.map((o) => `  ${o.id}: {\n    seed: ${o.seed},\n    queues: [\n${o.queues.map((q) => `      '${q}',`).join('\n')}\n    ],\n    solution: '${o.solution}',\n    stats: ${JSON.stringify(o.stats).replace(/"(\w+)":/g, '$1: ').replace(/,/g, ', ')},\n  },`).join('\n');
writeFileSync(new URL('./queues.js', import.meta.url),
`// Generated by gen-levels.mjs. Do not edit by hand; edit levels.js or the
// generator and run: node proto/lift/gen-levels.mjs
// stats: jars in the level, solver solution length in moves, nodes the solver
// expanded, and how often a casual random player clears it without help.
export const QUEUES = {
${body}
};
`);
