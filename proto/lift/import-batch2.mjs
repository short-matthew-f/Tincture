// Authoring tool (not loaded by the page): turns the batch 2 painted sources
// (proto/lift/art-batch2.json, PNGs on the lift-art-batch2 branch, never merged)
// into Lifting Table grids and writes art-batch2.js. No dependencies.
//
//   git archive origin/lift-art-batch2 src-png | tar -x -C /tmp/b2
//   node proto/lift/import-batch2.mjs /tmp/b2/src-png [--sheet out.png]
//
// The sources were painted with a margin on every side and a background snapped
// to one palette color, so they convert with no crop (the first batch's 10% zoom
// cut their edges). Each picture is converted at its slot's size in the
// chapters book-batch2.js lays out (slotSize: 18x24 up to 27x36).
import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { importPNG, contactSheet } from './import-art.mjs';
import { BOOK2, slotSize } from './book-batch2.js';

const args = process.argv.slice(2);
const dir = args[0];
const opt = (k, d) => { const i = args.indexOf(k); return i >= 0 ? args[i + 1] : d; };
if (!dir || !existsSync(dir)) {
  console.error('usage: node proto/lift/import-batch2.mjs <dir of batch 2 PNGs> [--sheet out.png]');
  process.exit(1);
}
const sheet = JSON.parse(readFileSync(new URL('./art-batch2.json', import.meta.url), 'utf8'));
const conv = { ...sheet.delivered.convert, crop: null };

// Rows as runs of a letter and its count when over one ("s3o2s3"), joined by "/".
const rle = (rows) => rows.map((r) => r.replace(/(.)\1*/g, (m, c) => c + (m.length > 1 ? m.length : ''))).join('/');

const out = [];
const grids = [];
const subject = Object.fromEntries(sheet.items.map((it) => [it.n, it]));
for (const ch of BOOK2) {
  ch.items.forEach((it, i) => {
    const [W, H] = slotSize(i, ch.items.length);
    const rows = importPNG(readFileSync(`${dir}/${it.file}`), { W, H, ...conv });
    grids.push([it.id, rows]);
    out.push(`  ${it.id}: '${rle(rows)}', // ${subject[it.n].n} ${subject[it.n].subject}, ${W}x${H}`);
  });
}
writeFileSync(new URL('./art-batch2.js', import.meta.url),
  `// Generated by import-batch2.mjs from the batch 2 painted sources (art-batch2.json;\n`
  + `// the PNGs live on the lift-art-batch2 branch). Do not edit by hand. One string a\n`
  + `// picture (rows joined by "/", runs as letter + length), at its slot's size, no crop.\n`
  + `export const ART_BATCH2 = {\n${out.join('\n')}\n};\n`);
if (opt('--sheet')) writeFileSync(opt('--sheet'), contactSheet(grids, 6, 12, 14));
console.log(`${grids.length} pictures written to proto/lift/art-batch2.js`);
